const LanguageContext = createContext(null);

function interpolate(value, variables = {}) {
  return Object.entries(variables).reduce(
    (result, [key, replacement]) => result.replaceAll(`{${key}}`, String(replacement)),
    value,
  );
}

function initialLanguage() {
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    if (saved === "en" || saved === "fr") return saved;
  } catch {
    // Storage can be unavailable in locked-down browser modes.
  }
  return window.navigator.language?.toLowerCase().startsWith("fr") ? "fr" : "en";
}

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(initialLanguage);
  const locale = language === "fr" ? "fr-FR" : "en-US";

  useEffect(() => {
    document.documentElement.lang = language;
    try {
      window.localStorage.setItem(STORAGE_KEY, language);
    } catch {
      // The current page still changes language when storage is unavailable.
    }
  }, [language]);

  const value = useMemo(() => ({
    language,
    locale,
    setLanguage,
    t(source, variables) {
      return interpolate(language === "fr" ? (fr[source] ?? source) : source, variables);
    },
    formatCents(cents = 0) {
      return new Intl.NumberFormat(locale, {
        style: "currency",
        currency: "USD",
        minimumFractionDigits: 2,
      }).format(cents / 100);
    },
    formatPrice(price = 0) {
      return new Intl.NumberFormat(locale, {
        style: "currency",
        currency: "USD",
        minimumFractionDigits: 2,
      }).format(price);
    },
    formatDate(value) {
      if (!value) return language === "fr" ? fr.Pending : "Pending";
      return new Intl.DateTimeFormat(locale, {
        month: "short",
        day: "2-digit",
        hour: "2-digit",
        minute: "2-digit",
      }).format(new Date(value));
    },
  }), [language, locale]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used inside LanguageProvider.");
  return context;
}

export function LanguageSwitch({ className = "" }) {
  const { language, setLanguage, t } = useLanguage();
  return (
    <div className={`language-switch ${className}`.trim()} role="group" aria-label={t("Language")}>
      <button type="button" className={language === "en" ? "is-active" : ""} aria-pressed={language === "en"} onClick={() => setLanguage("en")}>EN</button>
      <span>/</span>
      <button type="button" className={language === "fr" ? "is-active" : ""} aria-pressed={language === "fr"} onClick={() => setLanguage("fr")}>FR</button>
    </div>
  );
}

export function localizeError(message, t) {
  if (!message) return message;
  if (/security requirements|at least 8|too short/i.test(message)) return t("Use at least 8 characters for your password.");
  if (/already exists|already registered/i.test(message)) return t("An account with this email already exists. Sign in instead.");
  if (/expired/i.test(message) && /code|verification/i.test(message)) return t("That code expired. Request a new one below.");
  return t(message);
}
